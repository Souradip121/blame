// Writes torn.css: hand-torn paper edges as clip-path polygons (percent along an edge, px deep),
// so they stay the same depth at any size. Seeded, so re-running gives the same edges.
//   node tools/make-torn.mjs
import { writeFileSync } from 'node:fs';

let seed = 7;
const rnd = () => { seed = (seed * 16807) % 2147483647; return (seed - 1) / 2147483646; };
const r2 = (n) => Math.round(n * 100) / 100;

function edge(n, amp, rough = 1) {
  // a torn edge: a slow wander plus small bites
  const pts = [];
  let wander = rnd() * amp;
  for (let i = 0; i <= n; i++) {
    wander += (rnd() - 0.5) * amp * 0.7;
    wander = Math.max(0, Math.min(amp, wander));
    const bite = rnd() < 0.25 * rough ? rnd() * amp * 0.6 : 0;
    const t = i / n + (i > 0 && i < n ? (rnd() - 0.5) * (0.6 / n) : 0);
    pts.push([r2(t * 100), r2(Math.min(amp, wander + bite))]);
  }
  return pts;
}

function box({ n = 34, side = 5, amp = 5, ampSide = 3, rough = 1, top = true, bottom = true, left = true, right = true }) {
  const out = [];
  const T = top ? edge(n, amp, rough) : [[0, 0], [100, 0]];
  for (const [x, y] of T) out.push(`${x}% ${y}px`);
  const R = right ? edge(side, ampSide, rough) : [[0, 0], [100, 0]];
  for (const [y, x] of R.slice(1, -1)) out.push(`calc(100% - ${x}px) ${y}%`);
  const B = bottom ? edge(n, amp, rough) : [[0, 0], [100, 0]];
  for (const [x, y] of B.reverse()) out.push(`${x}% calc(100% - ${y}px)`);
  const L = left ? edge(side, ampSide, rough) : [[0, 0], [100, 0]];
  for (const [y, x] of L.reverse().slice(1, -1)) out.push(`${x}px ${y}%`);
  return `polygon(${out.join(', ')})`;
}

const vars = {
  '--torn-a': box({ amp: 6, ampSide: 4 }),
  '--torn-b': box({ amp: 7, ampSide: 5, n: 40 }),
  '--torn-c': box({ amp: 5, ampSide: 3, n: 30 }),
  '--torn-fiber': box({ amp: 9, ampSide: 6, n: 46, rough: 1.4 }),
  '--torn-strip': box({ amp: 4, ampSide: 6, n: 30, side: 7 }),
  '--torn-tape': box({ amp: 3, ampSide: 5, n: 22, side: 6 }),
  '--torn-foot': box({ amp: 16, n: 60, rough: 1.3, bottom: false, left: false, right: false }),
  '--torn-photo': box({ amp: 12, n: 56, rough: 1.2, top: false, left: false, right: false }),
};

const css = `/* generated by tools/make-torn.mjs: torn paper edges */\n:root {\n${Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`;
writeFileSync(new URL('../torn.css', import.meta.url), css);
console.log('torn.css', css.length, 'bytes');
